/*
 * The service catalogue.
 *
 * Fourteen services, each with its own page. Five of them are `featured` and
 * are the cards on the landing section — that split is deliberate: a section
 * showing all fourteen would be a price list, and the brief asks for five
 * cards and nothing else.
 *
 * RUSSIAN ONLY, and that is a decision rather than an oversight. The site's
 * chrome is trilingual, but these are fourteen service descriptions the owner
 * wrote; machine-translating them into Tajik and English would put words in
 * his mouth on his own commercial pages. The section's headings do go through
 * i18n, because those are short and already written in all three.
 *
 * Every page answers the same three questions in the same order, because the
 * owner asked for exactly that: what it is, what it gives you, who it is for.
 */

export interface Service {
  /** URL segment — /services/<slug>. */
  slug: string;
  /** Two digits. Decorative in the card, and the catalogue's own order. */
  num: string;
  title: string;
  /** One line under the title in the card. Two short clauses, no more. */
  tagline: string;
  /** What it is. */
  what: string;
  /** What it gives the client — the reason to buy it. */
  help: string;
  /** Who it suits. */
  who: string;
  /** Which of the five preview drawings this card uses, if featured. */
  preview?: 'laptop' | 'phone' | 'dashboard' | 'redesign' | 'orbit';
  featured?: boolean;
}

